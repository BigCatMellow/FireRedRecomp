-- Contract test for the narrowly scoped Phase 2 implementation-capture
-- harness.  Runtime capture remains ROM-backed and is exercised by its shell
-- script; this test protects the deterministic, no-reference-media protocol.
local function read(path)
  local f = assert(io.open(path, "rb"))
  local text = f:read("*a")
  f:close()
  return text
end

