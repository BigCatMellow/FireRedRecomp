assert(source:find('love.graphics.draw(world.phase2CaptureCanvas, 0, 0)', 1, true))
assert(source:find('love.graphics.captureScreenshot(function(imageData)', 1, true))
assert(source:find('if width ~= 240 or height ~= 160 then', 1, true))
assert(source:find('PHASE2_CAPTURE_SURFACE PASS anchor=%s dimensions=240x160', 1, true))
assert(source:find('love.window.setMode(240, 160, { resizable=false })', 1, true))
assert(source:find('local y = captureSurface and -10 or 20', 1, true))
assert(source:find('if not captureSurface then', 1, true))
assert(source:find('if captureSurface then borderOffsetPx = BORDER_MARGIN_METATILES * 16 end', 1, true))

